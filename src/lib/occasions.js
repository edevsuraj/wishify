export const CORE_OCCASIONS = OCCASIONS.filter((occasion) => occasion.group === 'everyday')
export const CULTURAL_OCCASIONS = OCCASIONS.filter((occasion) => occasion.group !== 'everyday')
export const FEATURED_OCCASIONS = OCCASIONS.filter((occasion) => occasion.featured)
export const OCCASION_MAP = Object.fromEntries(OCCASIONS.map((occasion) => [occasion.id, occasion]))
export const OCCASION_IDS = OCCASIONS.map((occasion) => occasion.id)
export const OCCASION_GROUP_MAP = Object.fromEntries(OCCASION_GROUPS.map((group) => [group.id, group]))
export const OCCASIONS_BY_GROUP = OCCASION_GROUPS.reduce((groups, group) => {
  groups[group.id] = OCCASIONS.filter((occasion) => occasion.group === group.id)
  return groups
}, {})

export function getOccasion(id) {
  return OCCASION_MAP[id] || null
}

export function getOccasionGroup(id) {
  const occasion = getOccasion(id)
  return occasion ? OCCASION_GROUP_MAP[occasion.group] : null
}

export function suggestionsFor(occasion, language = 'en') {
  if (!occasion) return []
  if (language === 'hi' && occasion.messagesHi?.length) return occasion.messagesHi
  return occasion.messages || []
}

export function headingsFor(occasion, language = 'en') {
  if (!occasion) return []
  if (language === 'hi' && occasion.headingsHi?.length) return occasion.headingsHi
  return occasion.headings || []
}

export function searchOccasions(query) {
  const term = query.trim().toLowerCase()
  if (!term) return OCCASIONS
  return OCCASIONS.filter((occasion) =>
    [
      occasion.label,
      occasion.tagline,
      occasion.blurb,
      occasion.group,
      occasion.heading,
      occasion.headings?.join(' '),
      occasion.headingsHi?.join(' '),
    ]
      .filter(Boolean)
      .join(' ')
      .toLowerCase()
      .includes(term),
  )
}
